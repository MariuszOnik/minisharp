#!/usr/bin/env python3
"""Embeds examples/*.cs and their assets (examples/*.png, *.wav), and the example projects
(examples/Name/...), into source3ds/samples.h, so the 3DS app can install them on first run."""
import glob, os
root = os.path.join(os.path.dirname(__file__), "..")


def c_string(data):
    """bytes -> C string literal lines; text stays readable, other bytes become octal escapes"""
    lines, cur = [], []
    for b in data:
        ch = chr(b)
        if ch == "\\": cur.append("\\\\")
        elif ch == '"': cur.append('\\"')
        elif ch == "\n":
            cur.append("\\n")
            lines.append("".join(cur)); cur = []
            continue
        elif 32 <= b < 127 and ch != "?": cur.append(ch)   # '?' avoids trigraphs
        else: cur.append("\\%03o" % b)
        if len(cur) >= 120: lines.append("".join(cur)); cur = []
    lines.append("".join(cur))
    return "\n    ".join('"%s"' % l for l in lines)


out = ["/* generated by tools/gen_samples.py - do not edit */",
       "static const struct { const char* name; const char* data; unsigned len; } ms_samples[] = {"]
files = []
for pattern in ("*.cs", "*.png", "*.wav"):
    files += glob.glob(os.path.join(root, "examples", pattern))      # single programs
    files += glob.glob(os.path.join(root, "examples", "*", pattern)) # projects: "Name/file"
examples = os.path.join(root, "examples")
for name in sorted(os.path.relpath(p, examples).replace(os.sep, "/") for p in files):
    data = open(os.path.join(examples, name), "rb").read()
    out.append('  { "%s", %d,\n    %s },' % (name, len(data), c_string(data)))
out.append("};")
# the struct puts len after data; emit fields in that order
text = "\n".join(out) + "\n"
text = text.replace('const char* data; unsigned len;', 'unsigned len; const char* data;')
open(os.path.join(root, "source3ds", "samples.h"), "w", encoding="utf-8", newline="\n").write(text)
