#!/usr/bin/env python3
"""Builds source3ds/help_data.h for the editor's Help: the language topics from sdk/Help.txt
and the API from sdk/MiniSharp.Api.cs (signatures and <summary> comments)."""
import os, re
root = os.path.join(os.path.dirname(__file__), "..")


def c_str(s):
    if s is None: return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("?", "\\?") + '"'


groups = []          # (name, doc, is_api)
entries = []         # (group, name, sig, doc, insert)

# ---- language topics: "## Title" then text ----
title, body = None, []
for line in open(os.path.join(root, "sdk", "Help.txt"), encoding="utf-8").read().splitlines() + ["## "]:
    if line.startswith("## "):
        if title: groups.append((title, "\n".join(body).strip(), 0))
        title, body = line[3:].strip(), []
    else:
        body.append(line)

# ---- API ----
summary, cls = None, None
for raw in open(os.path.join(root, "sdk", "MiniSharp.Api.cs"), encoding="utf-8"):
    line = raw.strip()
    m = re.match(r"/// <summary>(.*)</summary>", line)
    if m:
        summary = re.sub(r"</?\w+>", "", m.group(1)).replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
        continue
    m = re.match(r"public (?:static |sealed )*class (\w+)", line)
    if m:
        cls = m.group(1)
        groups.append((cls, summary or "", 1))
        summary = None
        if line.endswith("}"):           # "class WaitForSeconds { public WaitForSeconds(float s) { } }"
            c = re.search(r"\{ public \w+\((.*?)\)", line)
            sig = "new %s(%s)" % (cls, c.group(1) if c else "")
            entries.append((cls, cls, sig, groups[-1][1], "new %s(" % cls))
        continue
    m = re.match(r"public const (\w+) (.*);$", line)
    if m and cls:
        typ = m.group(1)
        for part in m.group(2).split(","):
            name, _, value = part.strip().partition(" = ")
            entries.append((cls, name, "const %s %s = %s" % (typ, name, value), summary or "", "%s.%s" % (cls, name)))
        summary = None
        continue
    m = re.match(r"public static (\S+) (\w+)\((.*?)\)", line)
    if m and cls:
        ret, name, params = m.groups()
        # StartCoroutine etc. are called without the class name
        insert = name + "(" if cls == "Coroutines" else "%s.%s(" % (cls, name)
        entries.append((cls, name, "%s %s(%s)" % (ret, name, params), summary or "", insert))
        summary = None
        continue
    if line == "}": cls = None

out = ["/* generated by tools/gen_help.py from sdk/Help.txt and sdk/MiniSharp.Api.cs - do not edit */",
       "typedef struct { const char* name; const char* doc; int api; } HelpGroup;",
       "typedef struct { const char* group; const char* name; const char* sig; const char* doc; const char* insert; } HelpEntry;",
       "static const HelpGroup ms_help_groups[] = {"]
out += ["    { %s, %s, %d }," % (c_str(n), c_str(d), a) for n, d, a in groups]
out += ["};", "static const HelpEntry ms_help[] = {"]
out += ["    { %s, %s, %s, %s, %s }," % tuple(map(c_str, e)) for e in entries]
out += ["};"]
open(os.path.join(root, "source3ds", "help_data.h"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("%d groups, %d entries" % (len(groups), len(entries)))
